def generate():
    os.makedirs('data', exist_ok=True)
    
    # 1. Export CSV
    csv_file = 'data/assam_personalities.csv'
    headers = [
        'id', 'name_english', 'name_assamese', 'era', 'approx_period',
        'primary_field', 'sub_field_roles', 'dynasty_movement_org',
        'key_achievements', 'notable_works_titles', 'region_association', 'gender'
    ]
    
    with open(csv_file, 'w', encoding='utf-8', newline='') as f:
        writer = csv.DictWriter(f, fieldnames=headers, quoting=csv.QUOTE_ALL)
        writer.writeheader()
        for p in personalities:
            writer.writerow(p)
            
    print(f"✅ Generated CSV at {csv_file} with {len(personalities)} entries.")
    
    # 2. Export JSON
    json_file = 'data/assam_personalities.json'
    dataset = {
        'title': 'Eminent Personalities of Assam: Ancient to Present',
        'description': 'A comprehensive, structured biographical dataset of notable historical, cultural, scientific, literary, and political figures of Assam.',
        'totalCount': len(personalities),
        'erasCovered': sorted(list(set(p['era'] for p in personalities))),
        'fieldsCovered': sorted(list(set(p['primary_field'] for p in personalities))),
        'personalities': personalities
    }
    
    with open(json_file, 'w', encoding='utf-8') as f:
        json.dump(dataset, f, ensure_ascii=False, indent=2)
        
    print(f"✅ Generated JSON at {json_file}.")

if __name__ == '__main__':
    generate()
